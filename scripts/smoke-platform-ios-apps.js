import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';

const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  const base = process.env.DINDBOS_QA_URL || 'http://127.0.0.1:5186/';
  await page.goto(new URL('scripts/fixtures/platform-apps.html?style=windows&mobileStyle=ios&width=390', base).href);
  await page.waitForFunction(() => window.platformAppsQA);
  const show = id => page.evaluate(id => window.platformAppsQA.show(id), id);
  await show('notes');
  const notes = page.locator('.dos-window[data-app-id=notes]');
  await expect(notes).toHaveAttribute('data-mobile-pane', 'list');
  await expect(notes.getByRole('searchbox', { name: 'Search notes', exact: true })).toBeVisible();
  await notes.getByRole('searchbox', { name: 'Search notes', exact: true }).fill('Project');
  await expect(notes.locator('[data-note-id=ideas]')).toHaveCount(0);
  await notes.getByRole('searchbox', { name: 'Search notes', exact: true }).fill('');
  await notes.locator('[data-note-id=plan]').click();
  await expect(notes).toHaveAttribute('data-mobile-pane', 'detail');
  await notes.getByRole('textbox', { name: 'Note text', exact: true }).fill('Draft remains after Back, Home and resize');
  await notes.getByRole('button', { name: 'Back to Notes', exact: true }).click();
  await expect(notes.locator('[data-note-id=plan]')).toBeFocused();
  await notes.locator('[data-note-id=plan]').click();
  await expect(notes.getByRole('textbox', { name: 'Note text', exact: true })).toHaveValue('Draft remains after Back, Home and resize');
  await page.getByRole('button', { name: 'Home', exact: true }).click();
  await show('notes');
  await expect(notes.getByRole('textbox', { name: 'Note text', exact: true })).toHaveValue('Draft remains after Back, Home and resize');
  await show('settings');
  const settings = page.locator('.dos-window[data-app-id=settings]');
  await expect(settings).toHaveAttribute('data-mobile-pane', 'list');
  await settings.locator('[data-settings-section-button=wallpaper]').click();
  await expect(settings).toHaveAttribute('data-mobile-pane', 'detail');
  await settings.getByRole('button', { name: 'Back to Settings', exact: true }).click();
  await expect(settings.locator('[data-settings-section-button=wallpaper]')).toBeFocused();
  await page.evaluate(() => window.platformAppsQA.os.shell.openSettings('appearance'));
  await expect(settings).toHaveAttribute('data-mobile-pane', 'detail');
  await page.locator('#platform-apps-host').evaluate(root => { root.style.width = '320px'; });
  await expect(settings.getByRole('button', { name: 'Back to Settings', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 1000, height: 900 });
  await page.locator('#platform-apps-host').evaluate(root => { root.style.width = '900px'; });
  await expect(page.locator('#platform-apps-host')).toHaveAttribute('data-ui-style', 'windows');
  await expect(page.locator('[data-mobile-app-back], [data-mobile-note-new]')).toHaveCount(0);
  assert.equal(await page.locator('[data-mobile-pane]').count(), 0);
  await expect(notes.locator('.notes-editor-toolbar .productivity-search')).toHaveCount(1);
  await expect(page.locator('[data-mobile-note-search]')).toHaveCount(0);
  await page.locator('#platform-apps-host').evaluate(root => { root.style.width = '390px'; });
  await expect(page.locator('#platform-apps-host')).toHaveAttribute('data-ui-style', 'ios');
  await expect(settings.locator('[data-mobile-app-back]')).toHaveCount(1);
  await page.evaluate(() => window.platformAppsQA.os.destroy());
  await expect(page.locator('[data-mobile-app-back], [data-mobile-note-new]')).toHaveCount(0);
  console.log('iOS app navigation passed: list/detail focus, saved drafts, Home, external Settings navigation, 320px, responsive cleanup and remount');
} finally { await browser.close(); }
