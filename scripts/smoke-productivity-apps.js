import assert from "node:assert/strict";
import { createProductivityStore } from "../src/dindbos/apps/productivity.js";
import { createDindbOSTestRuntime } from "./helpers/dindbos-test-runtime.js";
import { AppSandbox } from "../src/dindbos/app-sandbox.js";

const runtime = createDindbOSTestRuntime();
let syncs = 0;
runtime.storage = { status: () => ({ enabled: true }) };
runtime.flushPersistentFileSystem = async () => { syncs++; };
runtime.syscallAsync = (name, args, context) => runtime.syscalls.callAsync(name, args, context);
const sandbox = new AppSandbox(runtime, { pid: 7, appId: "notes", user: "guest", groups: ["users"], cwd: "/home/guest", manifest: { capabilities: ["storage.read"], fileSystem: { read: ["/home/guest"], write: ["/home/guest"] } } });
const errors = [];
const notes = createProductivityStore(sandbox, "notes", (error) => errors.push(error));
notes.set([{ id: "first", title: "Plan", body: "여러 줄\nA & B", updatedAt: new Date().toISOString() }]);
assert.equal(await notes.flush(), true);
assert.equal(syncs, 1);
assert.equal(createProductivityStore(sandbox, "notes").items[0].body, "여러 줄\nA & B");
assert.equal(sandbox.fs.stat("/home/guest/Documents/.dindbos/notes.json").owner, "guest");

runtime.flushPersistentFileSystem = async () => { throw new Error("disk unavailable"); };
notes.set([{ id: "first", title: "Not lost", body: "Still in memory" }]);
assert.equal(await notes.flush(), false);
assert.match(errors.at(-1), /Could not save.*disk unavailable/);
assert.equal(notes.items[0].title, "Not lost");
runtime.flushPersistentFileSystem = async () => { syncs++; };
assert.equal(await notes.flush(), true);
notes.dispose();
sandbox.fs.writeFile("/home/guest/Documents/.dindbos/notes.json", "broken JSON");
assert.throws(() => createProductivityStore(sandbox, "notes"));
assert.equal(sandbox.fs.readFile("/home/guest/Documents/.dindbos/notes.json"), "broken JSON", "malformed data is never overwritten");

const reminders = createProductivityStore(sandbox, "reminders");
let release;
let started;
const syncing = new Promise((resolve) => { started = resolve; });
runtime.flushPersistentFileSystem = async () => { started(); await new Promise((resolve) => { release = resolve; }); };
reminders.set([{ id: "a", title: "before", done: false }]);
const saving = reminders.flush();
await syncing;
reminders.set([{ id: "a", title: "during save", done: true }]);
runtime.flushPersistentFileSystem = async () => { syncs++; };
release();
assert.equal(await saving, true);
assert.equal(JSON.parse(sandbox.fs.readFile("/home/guest/Documents/.dindbos/reminders.json"))[0].title, "during save");
reminders.dispose();
const calendar = createProductivityStore(sandbox, "calendar");
let rejectSync;
runtime.flushPersistentFileSystem = () => new Promise((resolve, reject) => { rejectSync = reject; });
calendar.set([{ id: "event", title: "Keep draft" }]);
const firstFlush = calendar.flush();
const secondFlush = calendar.flush();
rejectSync(new Error("concurrent backend failure"));
assert.deepEqual(await Promise.all([firstFlush, secondFlush]), [false, false], "concurrent failed flushes always resolve false");
runtime.flushPersistentFileSystem = async () => {};
assert.equal(await calendar.flush(), true);
calendar.dispose();
console.log("productivity store smoke ok guest persistence, retry, corruption preservation and edits during flush");
